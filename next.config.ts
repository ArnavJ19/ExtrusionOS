import type { NextConfig } from "next";
import { getLocalDevelopmentSupabaseOrigin } from "./lib/security/local-development-csp";

const developmentScriptDirectives = process.env.NODE_ENV === "development" ? " 'unsafe-eval'" : "";
const defaultDistDir = process.env.NODE_ENV === "development" ? ".next-dev" : ".next";
const localSupabaseOrigin = getLocalDevelopmentSupabaseOrigin(process.env.NODE_ENV, process.env.NEXT_PUBLIC_SUPABASE_URL);
const localImageSource = localSupabaseOrigin ? ` ${localSupabaseOrigin}` : "";
const localConnectionSources = localSupabaseOrigin ? ` ${localSupabaseOrigin} ${localSupabaseOrigin.replace(/^http/, "ws")}` : "";

const contentSecurityPolicy = [
  "default-src 'self'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  `script-src 'self' 'unsafe-inline'${developmentScriptDirectives}`,
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self' data:",
  `img-src 'self' data: blob: https://*.supabase.co${localImageSource}`,
  `connect-src 'self' https://*.supabase.co wss://*.supabase.co${localConnectionSources}`,
  "worker-src 'self' blob:",
  "upgrade-insecure-requests",
].join("; ");

const nextConfig: NextConfig = {
  typedRoutes: false,
  // Keep Turbopack's live graph isolated when a production build runs beside next dev.
  distDir: process.env.NEXT_DIST_DIR || defaultDistDir,
  turbopack: {
    root: __dirname,
  },
  // Server PDFs read the Unicode font subsets and app-hosted company logos from disk
  // (lib/pdf/font-loader-node.ts, lib/pdf/logo-loader-node.ts): the
  // /api/pdf routes, and the die/profile technical sheets and PCDA reports generated by server
  // actions on these detail pages (lib/actions/pcda-reports.ts).
  outputFileTracingIncludes: {
    "/api/pdf/**/*": ["./public/fonts/pdf/**/*", "./public/brand/**/*"],
    "/dies/[id]": ["./public/fonts/pdf/**/*", "./public/brand/**/*"],
    "/profiles/[id]": ["./public/fonts/pdf/**/*", "./public/brand/**/*"],
    "/orders/[id]": ["./public/fonts/pdf/**/*", "./public/brand/**/*"],
    "/quotes/[id]": ["./public/fonts/pdf/**/*", "./public/brand/**/*"],
  },
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "X-Frame-Options", value: "DENY" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
          { key: "Content-Security-Policy", value: contentSecurityPolicy },
          { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
          { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
        ],
      },
    ];
  },
};

export default nextConfig;
