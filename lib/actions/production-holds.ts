"use server";

import { revalidatePath } from "next/cache";
import { getSessionContext } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import { canPlaceHolds, canReadHolds, holdCommandSchema, holdHistorySchema, readinessResponseSchema } from "@/lib/workflow/production-readiness";

export type HoldActionResult = { success: true; data: unknown } | { success: false; error: string; uncertain?: boolean; unavailable?: boolean };

const businessErrors = [
  "Record the hold reason, material condition and what permits resumption", "Choose an active production employee as the responsible person",
  "Production job is unavailable for this company", "The job status changed. Refresh before placing it on hold",
  "Only planned, ready or running jobs can be placed on hold", "The request identity was already used for different details",
  "Record what was done before resuming", "This hold was already resolved. Refresh before resuming", "The job is no longer on hold. Refresh before resuming",
  "Assign an extrusion press before starting or holding production"
];

// UPGRADE_EOS features 63 and 72. Company and actor come from the session; the RPC rechecks everything.
export async function productionHoldAction(input: unknown): Promise<HoldActionResult> {
  let mutation = false;
  let submitted = false;
  try {
    const context = await getSessionContext();
    const parsed = holdCommandSchema.safeParse(input);
    if (!parsed.success) return { success: false, error: parsed.error.issues[0]?.message ?? "Invalid hold request" };
    const { command, ...payload } = parsed.data;
    mutation = command === "holds.place" || command === "holds.resume";
    if (context.dealerId || !(mutation ? canPlaceHolds(context.role) : canReadHolds(context.role))) return { success: false, error: "You do not have permission to use this action." };
    const supabase = await createClient();
    submitted = true;
    const result = await supabase.rpc("production_hold_command", { p_command: command, p_payload: payload });
    if (result.error) {
      const code = result.error.code ?? "";
      const message = result.error.message ?? "";
      if (["PGRST202", "42883", "42P01"].includes(code)) return { success: false, unavailable: true, error: "Hold and readiness tools are not available on this database yet. The database upgrade must be applied first." };
      // UPGRADE_EOS feature 76: competency refusals explain what is missing.
      if (code === "42501" && (message.startsWith("You are not authorised for ") || message.includes(" requires supervision for you"))) return { success: false, error: message };
      if (code === "42501") return { success: false, error: "This action is not permitted for your current session." };
      // Readiness messages are generated by the database from current records; show them as written.
      if (code === "23514" && message.startsWith("Cannot resume yet.")) return { success: false, error: message };
      if (code === "23514" && message.startsWith("Review current customer requirements for ")) return { success: false, error: message };
      if (code === "P0001" || code === "23514") return { success: false, error: businessErrors.includes(message) ? message : "The action was rejected by current production rules. Refresh and review the job." };
      if (code === "55P03") return { success: false, error: "A production resource is being changed. Refresh and retry." };
      return { success: false, uncertain: mutation, error: mutation ? "Confirmation is unavailable. Retry the same request to check whether it was recorded." : "Current hold information could not be loaded. Retry to check it." };
    }
    const data = command === "holds.readiness" ? readinessResponseSchema.parse(result.data) : command === "holds.list" ? holdHistorySchema.parse(result.data) : result.data;
    if (mutation) {
      for (const path of ["/production", `/production/${payload.job_id}`, "/production/database", "/production/schedule"]) {
        try { revalidatePath(path); } catch { /* A confirmed write remains confirmed if cache refresh fails. */ }
      }
    }
    return { success: true, data };
  } catch {
    return { success: false, uncertain: mutation && submitted, error: mutation && submitted ? "Confirmation is unavailable. Retry the same request to check whether it was recorded." : "The hold request could not be completed. Check your session and retry." };
  }
}
