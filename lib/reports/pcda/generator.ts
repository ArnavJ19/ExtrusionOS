import { type PdfFontLoader } from "../../pdf/unicode-text.ts";
import { nodeFontLoader } from "../../pdf/font-loader-node.ts";
import { PDF_COLORS, PdfDocumentWriter } from "../../pdf/document-kit.ts";
import { pdfDateTime } from "../../pdf/format.ts";
import { NOT_CAPTURED_LABEL } from "../../pcda/labels.ts";
import type { ReportModel } from "./builder";
import { escapeCsvCell, neutralizeSpreadsheetFormula } from "../../utils/csv.ts";

export type GeneratedReportFile = {
  bytes: Uint8Array;
  contentType: string;
  extension: "pdf" | "csv" | "xls";
};

function normalizeCell(value: unknown): string {
  return String(value ?? "").replace(/\r?\n/g, " ").trim();
}

function reportRows(model: ReportModel): string[][] {
  const rows: string[][] = [
    ["Report", model.header.reportTitle],
    ["Company", model.header.companyName],
    ["GST", model.header.companyGst],
    ["Module", model.header.moduleName],
    ["Record Number", model.header.recordNumber],
    ["References", model.header.references],
    ["Revision", model.header.revisionNumber],
    ["Generated Date", model.header.generatedDate],
    ["Generated By", model.header.generatedBy],
    ["Approval Status", model.header.approvalStatus],
    [],
  ];

  for (const section of model.sections) {
    rows.push([section.title]);
    // Same wording as the PDF for a section with nothing recorded.
    if (!section.fields.length) {
      rows.push(["No data captured for this section.", ""], []);
      continue;
    }
    rows.push(["Field", "Value"]);
    for (const field of section.fields) {
      rows.push([field.label, typeof field.value === "boolean" ? (field.value ? "Yes" : "No") : String(field.value)]);
    }
    rows.push([]);
  }

  return rows;
}

export async function generatePDF(model: ReportModel, loadFont: PdfFontLoader = nodeFontLoader, options: { logo?: Uint8Array | null } = {}): Promise<GeneratedReportFile> {
  const header = model.header;
  // Optional header facts that were not captured are left out of the header block.
  const meaningful = (value: unknown) => value !== null && value !== undefined && String(value).trim() !== "" && value !== NOT_CAPTURED_LABEL;
  // Header and footer both print the model's generation instant in IST (the builder's
  // generatedDate is a server-locale date string, which is UTC on serverless hosts).
  const generatedAt = Number.isNaN(Date.parse(model.metadata?.generatedAt ?? "")) ? undefined : new Date(model.metadata.generatedAt);
  const doc = await PdfDocumentWriter.create({
    title: header.reportTitle.toUpperCase(),
    number: header.recordNumber,
    logo: options.logo ?? null,
    issuer: { name: header.companyName, lines: [meaningful(header.companyGst) ? `GSTIN: ${header.companyGst}` : null] },
    meta: [
      ["Record No.", header.recordNumber],
      ["Module", header.moduleName],
      ["Revision", meaningful(header.revisionNumber) ? String(header.revisionNumber) : null],
      ["Approval", header.approvalStatus],
      ["Generated by", header.generatedBy],
      ["Generated on", generatedAt ? pdfDateTime(generatedAt) : header.generatedDate]
    ],
    footerNote: "Generated from recorded data. Fields marked Not Captured were not recorded.",
    generatedAt,
    subject: `${header.reportTitle} ${header.recordNumber}`
  }, loadFont, model);

  if (meaningful(header.references)) {
    doc.fields([["References", header.references]], { columns: 1, labelRatio: 0.18 });
  }

  const signers = ["Prepared by", "Checked by", "Approved by"];
  for (const [index, section] of model.sections.entries()) {
    if (index === model.sections.length - 1) doc.closing(signers);
    // Sections with long narrative values print as a single column so text is not cramped.
    const long = section.fields.some((field) => String(field.value ?? "").length > 48 || field.label.length > 28);
    doc.sectionTitle(section.title, 36);
    if (!section.fields.length) {
      doc.paragraph("No data captured for this section.", { size: 8, color: PDF_COLORS.muted });
      doc.space(8);
      continue;
    }
    doc.fields(section.fields.map((field) => [field.label, typeof field.value === "boolean" ? (field.value ? "Yes" : "No") : String(field.value ?? "")]),
      { columns: long ? 1 : 2, labelRatio: long ? 0.28 : 0.45 });
  }

  doc.space(4);
  doc.signatures(signers);

  return {
    bytes: await doc.finish(),
    contentType: "application/pdf",
    extension: "pdf",
  };
}

export function generateCSV(model: ReportModel): GeneratedReportFile {
  const csv = reportRows(model).map((row) => row.map((cell) => escapeCsvCell(normalizeCell(cell))).join(",")).join("\n");
  return {
    // UTF-8 byte-order mark: Excel otherwise opens the file as ANSI and garbles ±, µ, ₹ and Indian scripts.
    bytes: new TextEncoder().encode(`﻿${csv}`),
    contentType: "text/csv;charset=utf-8",
    extension: "csv",
  };
}

function excelCell(value: unknown) {
  const text = neutralizeSpreadsheetFormula(normalizeCell(value)).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  // Excel turns long digit strings (e-way bills, phone and account numbers) into 3.41E+11 and drops
  // leading zeros, so those cells are kept as text. Ordinary figures stay numeric.
  const digits = text.replace(/[\s+-]/g, "");
  return /^\d+$/.test(digits) && (digits.length >= 11 || /^0\d/.test(digits) || /\s/.test(text))
    ? `<td class="text">${text}</td>`
    : `<td>${text}</td>`;
}

export function generateExcel(model: ReportModel): GeneratedReportFile {
  const rows = reportRows(model)
    .map((row) => {
      if (!row.length) return `<tr><td colspan="2"></td></tr>`;
      // A one-cell row is a section title, followed by its Field / Value header row.
      if (row.length === 1) return `<tr><td colspan="2" class="section">${excelCell(row[0]).replace(/^<td[^>]*>|<\/td>$/g, "")}</td></tr>`;
      if (row[0] === "Field" && row[1] === "Value") return `<tr><th>Field</th><th>Value</th></tr>`;
      return `<tr>${row.map((cell) => excelCell(cell)).join("")}</tr>`;
    })
    .join("");
  const style = "table{border-collapse:collapse;font-family:Calibri,Arial,sans-serif;font-size:10pt}td,th{border:0.5pt solid #c9cdd2;padding:2pt 6pt;vertical-align:top}"
    + "th{background:#e9ecef;font-weight:bold;text-align:left}.section{background:#d9dde2;font-weight:bold;font-size:11pt}.text{mso-number-format:\"\\@\"}";
  const htmlWorkbook = `<!doctype html><html><head><meta charset="utf-8" /><style>${style}</style></head><body><table><col width="260" /><col width="420" />${rows}</table></body></html>`;
  return {
    bytes: new TextEncoder().encode(htmlWorkbook),
    contentType: "application/vnd.ms-excel;charset=utf-8",
    extension: "xls",
  };
}

export async function storeReport(
  supabase: { storage: { from: (bucket: string) => { upload: (path: string, bytes: Uint8Array, options: { contentType: string; upsert: boolean }) => Promise<{ error: { message: string } | null }> } } },
  file: GeneratedReportFile,
  storagePath: string,
  bucket = "reports"
): Promise<void> {
  const { error } = await supabase.storage.from(bucket).upload(storagePath, file.bytes, {
    contentType: file.contentType,
    upsert: true,
  });
  if (error) {
    if (/bucket not found/i.test(error.message) && bucket === "reports") {
      throw new Error("Report upload failed: missing private reports storage bucket. Apply migration 20260515005900_reports_storage_bucket.sql.");
    }
    throw new Error(`Report upload failed: ${error.message}`);
  }
}
