import { PDFDocument, rgb } from "pdf-lib";
import { PdfTextKit, type PdfFontLoader } from "../../pdf/unicode-text.ts";
import { nodeFontLoader } from "../../pdf/font-loader-node.ts";
import type { ReportModel } from "./builder";
import { escapeCsvCell, neutralizeSpreadsheetFormula } from "../../utils/csv.ts";

export type GeneratedReportFile = {
  bytes: Uint8Array;
  contentType: string;
  extension: "pdf" | "csv" | "xls";
};

function normalizeCell(value: unknown): string {
  return String(value ?? "").replace(/\r?\n/g, " ").trim();
}

function reportRows(model: ReportModel): string[][] {
  const rows: string[][] = [
    ["Report", model.header.reportTitle],
    ["Company", model.header.companyName],
    ["GST", model.header.companyGst],
    ["Module", model.header.moduleName],
    ["Record Number", model.header.recordNumber],
    ["References", model.header.references],
    ["Revision", model.header.revisionNumber],
    ["Generated Date", model.header.generatedDate],
    ["Generated By", model.header.generatedBy],
    ["Approval Status", model.header.approvalStatus],
    [],
  ];

  for (const section of model.sections) {
    rows.push([section.title]);
    rows.push(["Field", "Value"]);
    for (const field of section.fields) {
      rows.push([field.label, String(field.value)]);
    }
    rows.push([]);
  }

  return rows;
}

export async function generatePDF(model: ReportModel, loadFont: PdfFontLoader = nodeFontLoader): Promise<GeneratedReportFile> {
  const pdf = await PDFDocument.create();
  const pageSize: [number, number] = [595.28, 841.89];
  const margin = 42;
  const lineHeight = 14;
  const textWidth = pageSize[0] - margin * 2;
  const header = model.header;
  const kit = await PdfTextKit.create(pdf, loadFont, [
    ...Object.values(header),
    ...model.sections.flatMap((section) => [section.title, ...section.fields.flatMap((field) => [field.label, String(field.value)])])
  ]);
  let page = pdf.addPage(pageSize);
  let y = page.getHeight() - margin;

  function ensureSpace(lines = 1) {
    if (y - lines * lineHeight < margin) {
      page = pdf.addPage(pageSize);
      y = page.getHeight() - margin;
      kit.draw(page, `${header.reportTitle} | ${header.recordNumber} (continued)`, { x: margin, y, size: 8, color: rgb(0.38, 0.38, 0.38) });
      y -= lineHeight;
    }
  }

  // Long values wrap to the page width instead of being cut at a fixed length (PDF-07).
  function draw(text: string, options: { size?: number; bold?: boolean; color?: ReturnType<typeof rgb>; indent?: number } = {}) {
    const size = options.size ?? 9;
    const indent = options.indent ?? 0;
    for (const line of kit.wrap(text, size, textWidth - indent, options.bold)) {
      ensureSpace();
      kit.draw(page, line, { x: margin + indent, y, size, bold: options.bold, color: options.color ?? rgb(0.12, 0.12, 0.12) });
      y -= Math.max(lineHeight, size + 4);
    }
  }

  draw(header.reportTitle, { size: 16, bold: true });
  draw(`${header.companyName} · GST: ${header.companyGst}`, { size: 10 });
  draw(`${header.moduleName} · ${header.recordNumber} · Rev ${header.revisionNumber}`, { size: 10 });
  if (header.references) draw(`References: ${header.references}`, { size: 9, color: rgb(0.38, 0.38, 0.38) });
  draw(`Generated ${header.generatedDate} by ${header.generatedBy}`, { size: 9, color: rgb(0.38, 0.38, 0.38) });
  draw(`Approval: ${header.approvalStatus}`, { size: 9, color: rgb(0.38, 0.38, 0.38) });
  y -= 8;

  for (const section of model.sections) {
    ensureSpace(3);
    draw(section.title, { size: 12, bold: true });
    if (!section.fields.length) {
      draw("No captured fields for this section.", { color: rgb(0.45, 0.45, 0.45) });
      y -= 4;
      continue;
    }
    for (const field of section.fields) {
      draw(`${field.label}: ${field.value}`, { indent: 0 });
    }
    y -= 4;
  }

  const pages = pdf.getPages();
  pages.forEach((current, index) => kit.drawRight(current, `Page ${index + 1} of ${pages.length}`, { right: pageSize[0] - margin, y: 24, size: 8, color: rgb(0.45, 0.45, 0.45) }));

  return {
    bytes: await pdf.save(),
    contentType: "application/pdf",
    extension: "pdf",
  };
}

export function generateCSV(model: ReportModel): GeneratedReportFile {
  const csv = reportRows(model).map((row) => row.map((cell) => escapeCsvCell(normalizeCell(cell))).join(",")).join("\n");
  return {
    bytes: new TextEncoder().encode(csv),
    contentType: "text/csv;charset=utf-8",
    extension: "csv",
  };
}

export function generateExcel(model: ReportModel): GeneratedReportFile {
  const rows = reportRows(model)
    .map((row) => `<tr>${row.map((cell) => `<td>${neutralizeSpreadsheetFormula(normalizeCell(cell)).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")}</td>`).join("")}</tr>`)
    .join("");
  const htmlWorkbook = `<!doctype html><html><head><meta charset="utf-8" /></head><body><table>${rows}</table></body></html>`;
  return {
    bytes: new TextEncoder().encode(htmlWorkbook),
    contentType: "application/vnd.ms-excel;charset=utf-8",
    extension: "xls",
  };
}

export async function storeReport(
  supabase: { storage: { from: (bucket: string) => { upload: (path: string, bytes: Uint8Array, options: { contentType: string; upsert: boolean }) => Promise<{ error: { message: string } | null }> } } },
  file: GeneratedReportFile,
  storagePath: string,
  bucket = "reports"
): Promise<void> {
  const { error } = await supabase.storage.from(bucket).upload(storagePath, file.bytes, {
    contentType: file.contentType,
    upsert: true,
  });
  if (error) {
    if (/bucket not found/i.test(error.message) && bucket === "reports") {
      throw new Error("Report upload failed: missing private reports storage bucket. Apply migration 0059_reports_storage_bucket.sql.");
    }
    throw new Error(`Report upload failed: ${error.message}`);
  }
}
