export const FLOOR_MESSAGES: Record<FloorLanguage, Record<FloorKey, string>> = { en, hi };

export function parseFloorLanguage(value: unknown): FloorLanguage { return value === "hi" ? "hi" : "en"; }

/** True when the catalogue has this key (for labels built from a record value, such as a task kind). */
export function isFloorKey(key: string): key is FloorKey { return Object.prototype.hasOwnProperty.call(en, key); }

export type FloorText = (key: FloorKey, vars?: Record<string, string | number | null | undefined>) => string;

/** A translator for one language; {name} placeholders are replaced, and a missing value shows as "—". */
export function floorText(language: FloorLanguage | null | undefined): FloorText {
  const messages = FLOOR_MESSAGES[parseFloorLanguage(language)];
  return (key, vars) => (messages[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars?.[name];
    return value === null || value === undefined || value === "" ? "—" : String(value);
  });
}
